import { CalculationResult, FirstMirror, StoryInputs, MeetingOfMirrorsResult } from '../types';

export function generateDeterministicMeeting(
  calc: CalculationResult,
  firstMirror: FirstMirror | undefined,
  inputs: StoryInputs,
  storyResult: any
): MeetingOfMirrorsResult {
  const soulNum = calc.soul;
  const pathNum = calc.path;
  const mainImage = inputs.q2 || "не назван";
  const innerTension = inputs.q1 || "внутреннее напряжение";
  const missingQuality = inputs.q4 || "недостающее качество";
  const momentOfLife = inputs.q3 || "момент ясности";

  return {
    summary: `Мы сопоставили два независимых отражения: структурную матрицу по дате вашего рождения (Душа ${soulNum}, Путь ${pathNum}) и образный мир, возникший из ваших четырёх ответов («${mainImage}»).`,
    hasStrongParallels: true,
    confidenceNote: "Обнаружено выраженное смысловое пересечение между потребностью вашей числовой формулы и выбранными метафорами.",
    parallels: [
      {
        theme: "Точка внутреннего напряжения и поиск опоры",
        codeAnchor: `Число Души ${soulNum} сталкивается с сопротивлением в зоне Направления (${calc.direction}): потребность держать контроль и отстаивать границы.`,
        mythAnchor: `В образном ответе прозвучало: «${innerTension}», а центральным символом стал «${mainImage}».`,
        synthesis: "Оба зеркала указывают на одну и ту же точку: внешнее напряжение возникает там, где старые способы удержания равновесия перестают работать и требуют нового взгляда."
      },
      {
        theme: "Ресурс подлинной живости и скрытый потенциал",
        codeAnchor: `Вектор Результата (${calc.result}) ориентирован на зрелую сборку опыта через реализацию истинного дара.`,
        mythAnchor: `В моменте максимальной живости вы вспомнили: «${momentOfLife}», а недостающим качеством назвали «${missingQuality}».`,
        synthesis: "Ваша дата и ваши живые воспоминания согласуются: сила возвращается ровно в те моменты, когда вы позволяете себе действовать из собственной природы, а не из чужих ожиданий."
      }
    ],
    divergences: [
      {
        theme: "Ракурс рассмотрения: долгосрочный маршрут vs сиюминутный фокус",
        codeAspect: `Код описывает макро-стратегию по линии Пути (${pathNum}), требующую выдержки и системности.`,
        mythAspect: `Миф фиксирует чуткое текущее переживание («${missingQuality}»), требующее немедленной паузы и мягкости к себе.`,
        reflection: "Это не противоречие, а разница масштабов: дата задаёт общий горизонт, а образный миф подсказывает, с чего именно нужно начать сегодня."
      }
    ],
    albertInsight: `Когда мы смотрим в оба зеркала одновременно, становится очевидно: ваша числовая архитектура (Душа ${soulNum}, Путь ${pathNum}) не случайна для человека, создавшего образ «${mainImage}». Вы обладаете высокой чувствительностью к форме и структуре. Главное открытие этой встречи — в том, что вам не нужно изобретать новую личность; достаточно дать вашему недостающему качеству («${missingQuality}») стать полноправным участником ваших ежедневных решений.`,
    reflectiveQuestion: `Если представить, что качество «${missingQuality}» уже есть внутри вас прямо сейчас — какое одно простое решение вы бы приняли иначе уже сегодня вечером?`,
    disclaimer: "Эти две версии появились независимо. Одна — из вашей даты, другая — из образов, выбранных вами. Совпадения между ними ничего не доказывают, но дают повод присмотреться к себе внимательнее."
  };
}
