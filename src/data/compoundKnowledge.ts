export function getCompoundFallback(value: number): CompoundKnowledge {
  const digits = value.toString().split('').map(v => parseInt(v, 10));
  let sum = digits.reduce((acc, curr) => acc + curr, 0);
  let root = sum;
  let formulaStr = digits.join(' + ') + ' → ' + sum;
  if (sum > 9 && sum !== 11 && sum !== 22 && sum !== 33) {
    const sumDigits = sum.toString().split('').map(v => parseInt(v, 10));
    root = sumDigits.reduce((acc, curr) => acc + curr, 0);
    if (root === 10) root = 1;
    formulaStr += ' → ' + root;
  }

  const partsText = digits.map(d => DIGIT_ESSENCE_MAP[d] || `${d}`).join(' и ');
  const rootText = DIGIT_ESSENCE_MAP[root] || `${root}`;

  return {
    value,
    root,
    digits,
    title: `${value}/${root}`,
    short: `Синтез ${digits.join(' + ')} рождает индивидуальный оттенок числа ${root}.`,
    formula: formulaStr,
    accent: `В этом составном числе соединяются ${partsText}, чтобы вместе раскрыть ${rootText}. Именно эта внутренняя формула объясняет, почему ваше проявление числа ${root} имеет свой особый характер и глубину.`,
    risk: `Риск рассинхронизации возникает, если одна из составляющих цифр (${digits.join(' или ')}) перетягивает одеяло на себя и мешает выйти к целостному итогу (${root}).`,
    recommendation: `Осознанно опереться на каждое слагаемое вашей формулы (${formulaStr}) и направить их энергию в русло зрелого архетипа ${root}.`
  };
}

export function getCompoundKnowledge(compoundStr: string): CompoundKnowledge {
  if (!compoundStr) return getCompoundFallback(1);
  const baseVal = parseInt(compoundStr.split('/')[0], 10);
  if (compoundKnowledge[baseVal.toString()]) {
    return compoundKnowledge[baseVal.toString()];
  }
  return getCompoundFallback(baseVal || 1);
}

