export function findGlossaryEntryByTerm(term: string): GlossaryEntry | undefined {
  const normalized = term.trim().toLowerCase();
  return ALL_GLOSSARY_ENTRIES.find(entry =>
    entry.aliases.includes(normalized) || entry.title.toLowerCase().includes(normalized)
  );
}
